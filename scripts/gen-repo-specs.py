#!/usr/bin/env python3
"""Generate per-repo mimus standard specs for the 9aia fleet.

Each clone under repos/ is its own family: the spec lives at
repos/<name>/specs/<name>.toml and composes with the workspace pack
(specs/base.toml) at sweep time via union matching — no `extends`
needed, so a spec stays meaningful when the repo is checked out
standalone.

The spec is a *snapshot of the intended standard*: files present
today that are structural (manifests, wiring, workspace anatomy)
become required `files`/`dirs`; everything else tracked becomes
coverage. Removing a structural file or adding an uncovered one
then fails `mimus standard` — that is the point.

Usage:
    gen-repo-specs.py            # dry-run: print the plan
    gen-repo-specs.py --apply    # write specs/ into each clone
    gen-repo-specs.py --repo tamias [--apply]

Regenerated repo specs leave the 9aia-standard pack payload stale —
follow with `scripts/sync-spec-pack.py --apply` (and bump the pack's
version in libraries/9aia-standard/tamias.yaml).
"""

import subprocess
import sys
from pathlib import Path

WS = Path(__file__).resolve().parent.parent
REPOS = WS / "repos"

# Repos that must not get a spec: archived on GitHub (read-only).
SKIP = {"strigi"}

# Top-level files that are structural — present means required.
STRUCTURAL_FILES = {
    # rust workspace
    "Cargo.toml", "Cargo.lock", "rust-toolchain.toml", "rustfmt.toml",
    "dist-workspace.toml",
    # js/ts app
    "package.json", "pnpm-lock.yaml", "pnpm-workspace.yaml",
    "bun.lock", "bun.lockb", "tsconfig.json", "vite.config.ts",
    "vitest.config.ts", "eslint.config.mjs", "eslint.config.js",
    "eslint.config.ts", "nuxt.config.ts", ".nuxtrc",
    # org wiring — present means the wiring is load-bearing
    "myco.toml", "mimus.toml", "sturn.toml", "kuda.toml",
    "tarsi.toml", "tamias.yml", "tamias.yaml", "cuora.toml",
    "skills-lock.json",
    # release/site/meta markers
    "renovate.json", ".release-it.json", "action.yml", "VERSION",
    ".env.example", "workspace.code-workspace",
}

# Top-level dirs that are structural — present means required.
STRUCTURAL_DIRS = {"crates", "xtask", "src", ".kuda"}

# Owned by specs/base.toml — never repeated in a repo spec.
FLOOR_FILES = {
    "README.md", "AGENTS.md", "SECURITY.md", "CONTRIBUTING.md",
    "cypera.toml", "LICENSE", ".gitignore", "CHANGELOG.md",
}

CATALOG = WS / "projects.yaml"


def catalog_names() -> set[str]:
    names = set()
    if CATALOG.is_file():
        for line in CATALOG.read_text().splitlines():
            s = line.strip()
            if s.startswith("- name:"):
                names.add(s.split(":", 1)[1].strip())
    return names


def tracked_top_level(repo: Path) -> tuple[list[str], list[str]]:
    out = subprocess.run(
        ["git", "-C", str(repo), "ls-files"],
        capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    files, dirs = set(), set()
    for rel in out:
        top = rel.split("/", 1)[0]
        if "/" in rel:
            dirs.add(top)
        else:
            files.add(top)
    return sorted(files), sorted(d for d in dirs if d)


def toml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def spec_for(name: str, files: list[str], dirs: list[str],
             cataloged: bool) -> str:
    files = [f for f in files if f not in FLOOR_FILES]
    req_files = [f for f in files if f in STRUCTURAL_FILES]
    cover_files = [f for f in files if f not in STRUCTURAL_FILES]
    req_dirs = [d for d in dirs if d in STRUCTURAL_DIRS]
    cover_dirs = [d for d in dirs if d not in STRUCTURAL_DIRS]

    has_cargo = "Cargo.toml" in files
    # remote_org/policy are base-floor claims — repo specs only add
    # the per-repo delta (catalog membership for projects.yaml
    # entries). Standalone runs lose the floor claims; sweeps don't.
    lasius = "\n[providers.lasius]\ncatalog   = true\n" if cataloged else ""
    cargo = (
        "\n[providers.cargo]\npatches = \"org-only\"\norg     = \"9aia\"\n"
        if has_cargo else ""
    )

    def arr(items: list[str]) -> str:
        return "[\n" + "".join(f"  {toml_str(i)},\n" for i in items) + "]"

    return f'''# specs/{name}.toml — {name} repo standard (9aia).
#
# GENERATED by scripts/gen-repo-specs.py — edit deliberately, then
# re-run the generator only to re-snapshot coverage. specs/ changes
# require an approved org proposal (see scripts/spec-guard.py).
#
# Composes with workspace specs/base.toml at sweep time via union
# matching — this file only declares the repo's own delta.

# proposal: proposal-0055  # org-ledger proposal authorizing this spec set

family   = "9aia/{name}"
match    = [{toml_str(name)}]
severity = "fail"

files = {arr(req_files)}

dirs = {arr(req_dirs)}

cover = {arr(cover_files)}

cover_dirs = {arr(cover_dirs)}
{lasius}{cargo}'''


def main() -> int:
    apply = "--apply" in sys.argv
    only = None
    if "--repo" in sys.argv:
        only = sys.argv[sys.argv.index("--repo") + 1]
    cataloged = catalog_names()

    plan = []
    for repo in sorted(REPOS.iterdir()):
        if only and repo.name != only:
            continue
        if not (repo / ".git").exists() or repo.name in SKIP:
            continue
        files, dirs = tracked_top_level(repo)
        text = spec_for(repo.name, files, dirs, repo.name in cataloged)
        target = repo / "specs" / f"{repo.name}.toml"
        plan.append((repo.name, target, text))

    for name, target, text in plan:
        status = "write" if apply else "would-write"
        print(f"{status:<11} {target.relative_to(WS)}")
        if apply:
            target.parent.mkdir(exist_ok=True)
            target.write_text(text)
    print(f"\n{len(plan)} spec(s) {'written' if apply else 'planned'}"
          f"{' — dry-run, pass --apply to write' if not apply else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
